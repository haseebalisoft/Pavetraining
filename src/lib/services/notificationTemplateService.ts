import "server-only";

import { readFile } from "fs/promises";
import path from "path";

import { getNotificationSettingsSync } from "@/lib/services/notificationConfig";

export const PAVE_EMAIL_LOGO_CID = "pave-logo";

/** Inline logo HTML for emails (paired with cid attachment from loadPaveLogoAttachment). */
export function emailLogoHtml(): string {
  return `<p style="margin:0 0 20px 0;">
<img src="cid:${PAVE_EMAIL_LOGO_CID}" alt="PAVE Training" width="160" style="display:block;width:160px;max-width:100%;height:auto;border:0;" />
</p>`;
}

/** Reads public/brand/pave-logo.png for inline email embedding. */
export async function loadPaveLogoAttachment(): Promise<{
  filename: string;
  contentType: string;
  content: string;
  encoding: "base64";
  contentId: string;
  isInline: true;
} | null> {
  try {
    const logoPath = path.join(process.cwd(), "public", "brand", "pave-logo.png");
    const bytes = await readFile(logoPath);
    return {
      filename: "pave-logo.png",
      contentType: "image/png",
      content: bytes.toString("base64"),
      encoding: "base64",
      contentId: PAVE_EMAIL_LOGO_CID,
      isInline: true,
    };
  } catch (error) {
    console.warn("[notifications] Could not load PAVE logo for email:", error);
    return null;
  }
}

function portalDocumentsUrl(): string | null {
  const settings = getNotificationSettingsSync();
  if (!settings.portalUrl) return null;
  return `${settings.portalUrl.replace(/\/$/, "")}/customer/documents`;
}

function portalMatrixUrl(): string | null {
  const settings = getNotificationSettingsSync();
  if (!settings.portalUrl) return null;
  return `${settings.portalUrl.replace(/\/$/, "")}/customer`;
}

export function documentUploadEmailTemplate(input: {
  companyName: string;
  candidateName?: string | null;
  documentType: string;
}): { subject: string; text: string; html: string } {
  const who = input.candidateName?.trim()
    ? `${input.companyName} / ${input.candidateName.trim()}`
    : input.companyName;
  const docsUrl = portalDocumentsUrl();
  const portalLine = docsUrl
    ? `Please log into the PAVE Training Portal to view it:\n${docsUrl}`
    : "Please log into the PAVE Training Portal to view it.";

  const subject = "New training document available";
  const text = [
    `A new document has been shared for ${who}.`,
    `Document type: ${input.documentType}`,
    "",
    portalLine,
  ].join("\n");

  const html = docsUrl
    ? `<p>A new document has been shared for <strong>${escapeHtml(who)}</strong>.</p>
<p>Document type: <strong>${escapeHtml(input.documentType)}</strong></p>
<p>Please log into the <a href="${escapeHtml(docsUrl)}">PAVE Training Portal</a> to view it.</p>`
    : `<p>A new document has been shared for <strong>${escapeHtml(who)}</strong>.</p>
<p>Document type: <strong>${escapeHtml(input.documentType)}</strong></p>
<p>Please log into the PAVE Training Portal to view it.</p>`;

  return { subject, text, html };
}

