export function testEmailTemplate(): {
  subject: string;
  text: string;
  html: string;
} {
  const settings = getNotificationSettingsSync();
  const subject = "PAVE Training Portal — test notification";
  const text = [
    "This is a test notification from the PAVE Training Portal.",
    settings.portalUrl ? `Portal: ${settings.portalUrl}` : "",
    `Sent at: ${new Date().toISOString()}`,
  ]
    .filter(Boolean)
    .join("\n");
  const html = settings.portalUrl
    ? `<p>This is a test notification from the PAVE Training Portal.</p>
<p>Portal: <a href="${escapeHtml(settings.portalUrl)}">${escapeHtml(settings.portalUrl)}</a></p>
<p>Sent at: ${escapeHtml(new Date().toISOString())}</p>`
    : `<p>This is a test notification from the PAVE Training Portal.</p>
<p>Sent at: ${escapeHtml(new Date().toISOString())}</p>`;
  return { subject, text, html };
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
